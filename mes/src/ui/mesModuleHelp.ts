function escapeHtml(value:unknown):string {
  return String(value??'').replace(/[&<>\\"']/g,(ch)=>({'&':'&amp;','<':'&lt;','>':'&gt;','\\"':'&quot;',"'":'&#39;'}[ch]??ch));
}
function normalize(value:string):string { return value.replace(/\s+/g,' ').trim().toLowerCase(); }

function selectorFor(key:string):string {
  const selectors:Record<string,string>={
    dashboard:'.mes-dashboard-page','operational-workflow':'.operational-workflow-page','production-entry':'.production-entry-page',
    'operator-downtime':'.operator-downtime-page',equipment:'.equipment-operations-page',gantt:'.dispatch-gantt-page',
    orders:'.orders-page',requests:'.production-requests-page',plans:'.operational-plans-page',quality:'.quality-page',
    events:'.event-journal-page',integrity:'.integrity-page','workflow-monitor':'.workflow-monitor-page',
    import:'.import-center-page','user-admin':'.mes-user-admin-page',maintenance:'.maintenance-panel'
  };
  return selectors[key]??'';
}

function findTarget(root:HTMLElement,definition:HelpDefinition):HTMLElement|null {
  const selector=selectorFor(definition.key);
  if(selector){
    const direct=root.querySelector<HTMLElement>(selector);
    if(direct)return direct;
  }
  const titles:Record<string,string[]>={
    nsi:['нси mes','технологическая нси'],
    import:['центр импорта нси'],
    'production-entry':['рабочее место оператора'],
    gantt:['диспетчеризация · gantt'],
    events:['журнал производственных событий'],
    integrity:['контроль целостности mes'],
    'user-admin':['доступ к mes']
  };
  const needles=titles[definition.key]??[];
  for(const heading of Array.from(root.querySelectorAll<HTMLElement>('h2,h3'))){
    const headingText=normalize(heading.textContent??'');
    if(!needles.some(needle=>headingText.includes(needle)))continue;
    return heading.closest<HTMLElement>('section.panel,.panel,section')??heading.parentElement;
  }
  return null;
}

function render(definition:HelpDefinition):string {
  const steps=definition.steps.map(step =>
    '<div class="mes-help-step"><div class="mes-help-step-title">'+escapeHtml(step.title)+'</div><div class="mes-help-step-text">'+escapeHtml(step.text)+'</div></div>'
  ).join('');
  const note=definition.note
    ? '<div class="mes-help-note"><strong>Важно:</strong> '+escapeHtml(definition.note)+'</div>'
    : '';
  return '<div class="mes-help" data-mes-help="1">'+
    '<button type="button" class="mes-help-toggle" aria-expanded="false">'+
      '<span class="mes-help-toggle-main"><span class="mes-help-info">i</span><span>Справка: '+escapeHtml(definition.title)+' <span class="mes-help-hint">— нажмите, чтобы развернуть</span></span></span>'+
      '<span class="mes-help-chevron">⌄</span>'+
    '</button>'+
    '<div class="mes-help-content" hidden>'+
      '<div class="mes-help-intro">'+escapeHtml(definition.intro)+'</div>'+
      '<div class="mes-help-steps">'+steps+'</div>'+
      note+
    '</div>'+
  '</div>';
}

function bindOne(host:HTMLElement,definition:HelpDefinition):void {
  if(host.querySelector('[data-mes-help="1"]'))return;
  host.dataset.mesHelpBound='1';
  host.insertAdjacentHTML('afterbegin',render(definition));
  const help=host.querySelector<HTMLElement>('[data-mes-help="1"]');
  const button=help?.querySelector<HTMLButtonElement>('.mes-help-toggle');
  const content=help?.querySelector<HTMLElement>('.mes-help-content');
  if(!button||!content)return;
  button.addEventListener('click',()=>{
    const expanded=button.getAttribute('aria-expanded')==='true';
    button.setAttribute('aria-expanded',String(!expanded));
    content.hidden=expanded;
    help?.classList.toggle('expanded',!expanded);
  });
}

export function bindMesModuleHelp(root:HTMLElement):void {
  const apply=():void => {
    for(const definition of HELP){
      const host=findTarget(root,definition);
      if(host)bindOne(host,definition);
    }
  };
  apply();
  const observer=new MutationObserver(apply);
  observer.observe(root,{childList:true,subtree:true});
}
