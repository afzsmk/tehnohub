-- Qualification-specific equipment access.
-- A qualification may authorize an employee to work only on selected equipment.
create table if not exists qualification_equipment_access (
  id bigint generated by default as identity primary key,
  qualification_id text not null references qualification_levels(id) on delete cascade,
  equipment_id text not null references equipment(id) on delete cascade,
  valid_from date,
  valid_to date,
  notes text,
  created_at timestamptz not null default now(),
  constraint qualification_equipment_access_unique unique (qualification_id, equipment_id),
  constraint qualification_equipment_access_validity check (
    valid_to is null or valid_from is null or valid_to >= valid_from
  )
);

create index if not exists idx_qualification_equipment_access_qualification
  on qualification_equipment_access(qualification_id);
create index if not exists idx_qualification_equipment_access_equipment
  on qualification_equipment_access(equipment_id);

alter table qualification_equipment_access enable row level security;
revoke all on qualification_equipment_access from anon;
grant select on qualification_equipment_access to authenticated;
drop policy if exists qualification_equipment_access_select_authenticated on qualification_equipment_access;
create policy qualification_equipment_access_select_authenticated
  on qualification_equipment_access
  for select to authenticated
  using (true);

create or replace function public.mes_master_save_qualification_equipment_access(
  p_id bigint default null,
  p_qualification_id text,
  p_equipment_id text,
  p_valid_from date default null,
  p_valid_to date default null,
  p_notes text default null
) returns qualification_equipment_access
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  r qualification_equipment_access%rowtype;
begin
  perform mes_require_master_editor();

  if not exists (
    select 1 from qualification_levels
    where id = trim(p_qualification_id) and active
  ) then
    raise exception 'Активная квалификация не найдена: %', p_qualification_id;
  end if;

  if not exists (
    select 1 from equipment
    where id = trim(p_equipment_id) and active
  ) then
    raise exception 'Активное оборудование не найдено: %', p_equipment_id;
  end if;

  if p_valid_from is not null and p_valid_to is not null and p_valid_to < p_valid_from then
    raise exception 'Дата окончания допуска не может быть раньше даты начала';
  end if;

  insert into qualification_equipment_access(
    id, qualification_id, equipment_id, valid_from, valid_to, notes
  ) values (
    p_id,
    trim(p_qualification_id),
    trim(p_equipment_id),
    p_valid_from,
    p_valid_to,
    nullif(trim(p_notes), '')
  )
  on conflict (qualification_id, equipment_id) do update set
    valid_from = excluded.valid_from,
    valid_to = excluded.valid_to,
    notes = excluded.notes
  returning * into r;

  return r;
end;
$$;

